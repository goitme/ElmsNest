def strip_html(h):
    h = re.sub(r'<style[^>]*>.*?</style>', '', h, flags=re.S)
    h = re.sub(r'<[^>]+>', ' ', h)
    h = html.unescape(h)
    return re.sub(r'\s+', ' ', h)

def norm(s):
    return re.sub(r'\s+', ' ', s.replace('•', '').replace('…', '')).strip()

def words(s):
    return [w for w in re.split(r'\s+', s) if re.search(r'[A-Za-z0-9֐-׿]', w)]

